int removeDuplicates(int* nums, int numsSize) {
    if (numsSize == 0) {
        return 0;
    }

    int slow = 0;  // 慢指针：标记「无重复区域的最后一个位置」
    int fast = 1;  // 快指针：遍历整个数组

    while (fast < numsSize) {
        if (nums[fast] == nums[slow]) {
            // 重复：只移动快指针，继续找下一个
            fast++;
        }
        else {
            // 不重复：慢指针后移，把快指针的值覆盖过来
            slow++;
            nums[slow] = nums[fast];
            fast++;
        }
    }

    // 无重复元素的长度 = slow + 1（因为slow从0开始）
    return slow + 1;
}
/*
个人笔记：
此解法是个人理解做出的，说思路：针对边界条件快慢指针相等时，
慢指针充当标记指针停留标记位置，快指针继续前进，直至快指针与标记指针不相等
此时标记指针的后一位被快指针覆盖，快指针继续前进，直到快指针走到尽头numsSize
时间复杂度：O(n)
空间复杂度：O(1)
*/
